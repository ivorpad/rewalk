// rewalk doctor — verify every link of the install chain, name the fix.
//
// Written because "it doesn't work" on a fresh machine decomposes into eight
// different single-step failures (missing compiler, stale boot.main.js, moved
// checkout breaking the host wrapper, no mic grant...), and each one has a
// known one-line fix. The installer prints the steps once; this re-derives the
// state any time. Checks never mutate anything.
//
//   rewalk doctor        (or: node bin/doctor.mjs)
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync, spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { bootScript } from '../lib/record.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const REPO = path.resolve(ROOT, '..')
const HOME = os.homedir()
const CONFIG_DIR = process.env.REWALK_CONFIG_DIR ?? path.join(HOME, '.config/rewalk')

let fails = 0
const say = (state, name, detail, fix) => {
  const tag = state === 'ok' ? 'PASS' : state === 'warn' ? 'WARN' : state === 'info' ? 'info' : 'FAIL'
  if (state === 'fail') fails++
  console.log(`${tag}  ${name.padEnd(22)} ${detail}`)
  if (fix && state !== 'ok' && state !== 'info') console.log(`      fix: ${fix}`)
}
const sh = (cmd, args) => {
  try { return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }) }
  catch (e) { return e.stdout ?? '' }
}
// codesign -dv reports on STDERR even on success; spawnSync keeps it either way
const shBoth = (cmd, args) => {
  const r = spawnSync(cmd, args, { encoding: 'utf8' })
  return `${r.stdout ?? ''}${r.stderr ?? ''}`
}

// --- node ---------------------------------------------------------------
const major = +process.versions.node.split('.')[0]
say(major >= 18 ? 'ok' : 'fail', 'node', `${process.version} at ${process.execPath}`,
  'install Node >= 18')

// --- js deps --------------------------------------------------------------
say(fs.existsSync(path.join(ROOT, 'node_modules')) ? 'ok' : 'fail', 'deps (product)',
  path.join(ROOT, 'node_modules'), `cd ${ROOT} && npm install`)
say(fs.existsSync(path.join(ROOT, 'skill/node_modules/playwright')) ? 'ok' : 'warn', 'deps (engine)',
  'playwright for run/map/replay/watch', `cd ${path.join(ROOT, 'skill')} && npm install`)

// --- boot.main.js: byte-compare against what build.mjs would write NOW.
// Content, not mtimes: a git checkout refreshes mtimes without changing bytes.
const boot = path.join(ROOT, 'chrome-ext/src/boot.main.js')
if (!fs.existsSync(boot)) {
  say('fail', 'extension bundle', 'chrome-ext/src/boot.main.js missing (generated, gitignored)',
    `node ${path.join(ROOT, 'chrome-ext/build.mjs')}`)
} else {
  const want = `// GENERATED by chrome-ext/build.mjs from ../lib — do not edit by hand.\n${bootScript({ mask: true, hud: true, transport: 'event' })}\n`
  const fresh = fs.readFileSync(boot, 'utf8') === want
  say(fresh ? 'ok' : 'fail', 'extension bundle',
    fresh ? 'boot.main.js matches lib/ byte-for-byte' : 'STALE — lib/ has changed since the last build',
    `node ${path.join(ROOT, 'chrome-ext/build.mjs')}  — then reload the extension (chrome://extensions)`)
}

const darwin = process.platform === 'darwin'
if (!darwin) {
  say('info', 'voice', 'not macOS — voice capture unavailable; DOM recording still works')
} else {
  // --- signing identity + the two TCC apps ---------------------------------
  const ids = sh('security', ['find-identity', '-v', '-p', 'codesigning'])
  const hasIdentity = ids.includes('rewalk signing')
  say(hasIdentity ? 'ok' : 'warn', 'signing identity',
    hasIdentity ? '"rewalk signing" in keychain' : 'no "rewalk signing" identity (ad-hoc grants die on rebuild)',
    `sh ${path.join(ROOT, 'lib/mac/build-apps.sh')}  (creates it; one keychain trust dialog)`)

  for (const app of ['rewalk-mic', 'rewalk-voiced']) {
    const bin = path.join(ROOT, `lib/mac/${app}.app/Contents/MacOS/${app}`)
    if (!fs.existsSync(bin)) {
      say('fail', app, 'not built', `sh ${path.join(ROOT, 'lib/mac/build-apps.sh')}  (needs Xcode CLT: xcode-select --install)`)
      continue
    }
    const sig = shBoth('codesign', ['-dvv', path.join(ROOT, `lib/mac/${app}.app`)])
    const signed = /Authority=rewalk signing/.test(sig)
    const adhoc = /Signature=adhoc/.test(sig)
    say(signed ? 'ok' : adhoc ? 'warn' : 'fail', app,
      signed ? 'built, signed by "rewalk signing"' : adhoc ? 'built but AD-HOC signed — mic grant dies on next rebuild' : 'built, signature unreadable',
      `sh ${path.join(ROOT, 'lib/mac/build-apps.sh')}`)
  }

  // --- native messaging host: manifest -> wrapper -> node -> host script ----
  const manifest = path.join(HOME, 'Library/Application Support/Google/Chrome/NativeMessagingHosts/com.rewalk.host.json')
  if (!fs.existsSync(manifest)) {
    say('fail', 'native host', 'manifest not installed (extension cannot start a recording)',
      `sh ${path.join(ROOT, 'chrome-ext/host/install.sh')}  (read it first)`)
  } else {
    let ok = false, detail = ''
    try {
      const m = JSON.parse(fs.readFileSync(manifest, 'utf8'))
      const wrapper = m.path
      if (!fs.existsSync(wrapper)) detail = `wrapper missing: ${wrapper} (checkout moved?)`
      else {
        const w = fs.readFileSync(wrapper, 'utf8')
        const nodePath = (w.match(/exec "([^"]+)"/) ?? [])[1]
        const hostScript = (w.match(/exec "[^"]+" "([^"]+)"/) ?? [])[1]
        if (nodePath && !fs.existsSync(nodePath)) detail = `baked node gone: ${nodePath}`
        else if (hostScript && !fs.existsSync(hostScript)) detail = `host script gone: ${hostScript} (checkout moved?)`
        else { ok = true; detail = `manifest -> ${wrapper}` }
      }
      const extId = fs.readFileSync(path.join(ROOT, 'chrome-ext/host/.ext_id'), 'utf8').trim()
      if (ok && !JSON.stringify(m.allowed_origins ?? []).includes(extId)) {
        ok = false; detail = `manifest allows ${m.allowed_origins}, repo id is ${extId}`
      }
    } catch (e) { detail = `unreadable: ${e.message}` }
    say(ok ? 'ok' : 'fail', 'native host', detail, `sh ${path.join(ROOT, 'chrome-ext/host/install.sh')}`)
  }

  // --- login daemon (optional) ----------------------------------------------
  const plist = path.join(HOME, 'Library/LaunchAgents/com.rewalk.voiced.plist')
  if (!fs.existsSync(plist)) {
    say('info', 'daemon', 'not installed (optional; toolbar-only sessions need the companion instead)')
  } else {
    const loaded = sh('launchctl', ['list']).includes('com.rewalk.voiced')
    say(loaded ? 'ok' : 'warn', 'daemon', loaded ? 'com.rewalk.voiced loaded' : 'plist present but not loaded',
      `launchctl bootstrap gui/$(id -u) ${plist}`)
  }
}

// --- comments: hub + agent hooks ---------------------------------------------
// The hub is started on demand by the SessionStart hook, so "not running" is
// normal and not a failure. What IS a failure is hooks that are absent (no
// comment can ever reach an agent) or that point at a checkout that moved.
{
  const { hubAlive, sockPath, hubStateDir } = await import('../lib/hub-wire.mjs')
  const sock = sockPath()
  // macOS AF_UNIX paths cap near 104 bytes; the sibling project hit exactly
  // this with a longer prefix, so measure rather than assume.
  if (sock.length > 100) say('fail', 'hub socket', `path is ${sock.length} bytes — macOS caps AF_UNIX near 104`,
    'set REWALK_HUB_SOCK to something shorter')
  else {
    const up = await hubAlive()
    say(up ? 'ok' : 'info', 'hub', up ? `running, socket ${sock}` : `not running (normal — starts on demand). socket ${sock}`)
  }

  const queue = path.join(hubStateDir(), 'queue.json')
  if (fs.existsSync(queue)) {
    try {
      const q = JSON.parse(fs.readFileSync(queue, 'utf8'))
      const by = {}
      for (const c of q.comments ?? []) by[c.status] = (by[c.status] ?? 0) + 1
      const parts = Object.entries(by).map(([k, v]) => `${v} ${k}`)
      say('info', 'comment queue', parts.length ? parts.join(', ') : 'empty')
    } catch (e) { say('warn', 'comment queue', `unreadable: ${queue}`, `rm ${queue}`) }
  }

  // Which commands are installed, and do they still resolve? A hook naming a
  // moved checkout fails silently on every tool call, which looks exactly like
  // no hooks at all.
  const settings = path.join(HOME, '.claude/settings.json')
  let found = 0, broken = ''
  try {
    const s = JSON.parse(fs.readFileSync(settings, 'utf8'))
    for (const groups of Object.values(s.hooks ?? {}))
      for (const g of groups ?? [])
        for (const h of g.hooks ?? []) {
          const cmd = String(h.command ?? '')
          if (!/rewalk-hook|bin\/hook\.mjs/.test(cmd)) continue
          found++
          const first = cmd.split(' ')[0]
          const script = cmd.match(/(\S*bin\/hook\.mjs)/)?.[1]
          if (first && first.startsWith('/') && !fs.existsSync(first)) broken = `${first} is gone`
          else if (script && !fs.existsSync(script)) broken = `${script} is gone (checkout moved?)`
        }
  } catch (e) {}
  say(found >= 4 && !broken ? 'ok' : found ? 'warn' : 'fail', 'agent hooks',
    broken ? `${found} entr${found === 1 ? 'y' : 'ies'} but ${broken}`
      : found ? `${found} of 4 entries in ${settings}` : `none in ${settings} — comments can never reach an agent`,
    `node ${path.join(ROOT, 'bin/install-hooks.mjs')}`)
}

// --- config + key -----------------------------------------------------------
say(fs.existsSync(path.join(CONFIG_DIR, 'config.json')) ? 'ok' : 'warn', 'config',
  path.join(CONFIG_DIR, 'config.json'),
  `node ${path.join(ROOT, 'bin/ensure-config.mjs')} ${path.join(CONFIG_DIR, 'config.json')}`)
const key = path.join(CONFIG_DIR, 'deepgram.key')
say('info', 'deepgram', fs.existsSync(key) && fs.statSync(key).size > 1
  ? `key present (${key})` : 'no key — DOM-only sessions; live voice-to-text needs one')

// --- what a script cannot see ------------------------------------------------
console.log(`
Only a human can verify these two:
  chrome://extensions — the rewalk extension loaded (Load unpacked -> ${path.join(ROOT, 'chrome-ext')})
  rewalk mic 6        — the TCC grant; READY means the mic is heard, 0.000000 means denied
`)
process.exit(fails ? 1 : 0)
